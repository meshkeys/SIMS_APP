export type HttpMethod = 'get' | 'post' | 'put' | 'patch' | 'delete';

/**
 * Who may call a route: anyone (`public`), any signed-in member (`member`),
 * or members holding one of the listed roles. Finer rules (e.g. "the
 * initiative's owner") are enforced by the service and described in
 * `description`.
 */
export type Access = 'public' | 'member' | readonly Role[];

export interface ApiRoute {
  method: HttpMethod;
  /** Relative to `/api/v1`, with `{param}` placeholders (all ids are UUIDs). */
  path: string;
  tag: string;
  summary: string;
  description?: string;
  access: Access;
  /** Stricter per-IP limit (sign-in, sign-up, refresh, invitation tokens). */
  strictRateLimit?: boolean;
  query?: z.ZodObject;
  body?: z.ZodType;
  status: 200 | 201 | 204;
  /** null: no JSON body (204, or a file — see `produces`). */
  response: z.ZodType | null;
  /** A file download instead of JSON, e.g. an Excel export. */
  produces?: string;
  /** A file upload (multipart/form-data) in this form field instead of a JSON body. */
  uploadField?: string;
}

const route = <const R extends ApiRoute>(definition: R) => definition;

