export interface InitiativeSpec {
  code: string;
  title: string;
  /** Home objective (primary link). */
  objective: string;
  /** Extra objectives this initiative contributes to, with explicit weights. */
  alsoContributesTo?: { objective: string; weight: number }[];
  owner: PersonKey | null;
  sponsor: PersonKey;
  benefitsOwner?: PersonKey;
  start: string;
  end: string;
  /** Verified weighted completion, 0–100. */
  progress: number;
  /** Planned completion today, 0–100. */
  planned: number;
  health: Health;
  status?: InitiativeStatus;
  /** % of expected impact achieved; null = not yet measurable. */
  impact: number | null;
  impactSummary?: string;
  priority?: number;
  isSensitive?: boolean;
  /** Last update date (YYYY-MM-DD); defaults by position. */
  lastUpdate?: string;
  /** Explicit milestones; otherwise four standard phases are generated. */
  milestones?: MilestoneSeed[];
}

const m = (
  title: string,
  weight: number,
  start: string,
  baseline: string,
  verified: number,
  extra: Partial<MilestoneSeed> = {},
): MilestoneSeed => ({
  title,
  weight,
  baselineStartDate: date(start),
  baselineDate: date(baseline),
  verifiedCompletion: verified,
  claimedCompletion: verified,
  status:
    verified >= 100 ? 'COMPLETE' : verified > 0 ? 'IN_PROGRESS' : 'NOT_STARTED',
  ...extra,
});

